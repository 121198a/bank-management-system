// Generates docs/upgrade/API_ENDPOINTS.md from the real Express router (no DB needed).
// Usage: node scripts/list-routes.js
process.env.NODE_ENV = process.env.NODE_ENV || 'test';
process.env.JWT_ACCESS_SECRET = process.env.JWT_ACCESS_SECRET || 'x'.repeat(40);
process.env.JWT_REFRESH_SECRET = process.env.JWT_REFRESH_SECRET || 'y'.repeat(40);
process.env.MONGO_URI = process.env.MONGO_URI || 'mongodb://127.0.0.1/unused';
const fs = require('fs');
const path = require('path');
const app = require('../src/app');
const authModule = require('../src/middleware/auth');
const authenticate = authModule.authenticate || authModule;

const prefixFromRegexp = (re) => {
  const m = re.source.match(/^\^\\\/(.+?)\\\/\?\(\?=\\\/\|\$\)/);
  return m ? '/' + m[1].replace(/\\\//g, '/') : '';
};

const collectRoutes = () => {
const rows = [];
const guardOf = (handle) => ({
  jwt: handle === authenticate,
  roles: Array.isArray(handle.allowedRoles) ? handle.allowedRoles : null
});

// `inherited` = guards applied by enclosing routers; router.use() guards apply to
// every route declared AFTER them in the same router.
const walk = (stack, prefix, inherited) => {
  let jwt = inherited.jwt;
  let roles = inherited.roles;
  for (const layer of stack) {
    if (layer.route) {
      let rJwt = jwt;
      let rRoles = roles;
      for (const l of layer.route.stack) {
        const g = guardOf(l.handle);
        if (g.jwt) rJwt = true;
        if (g.roles) rRoles = g.roles;
      }
      for (const method of Object.keys(layer.route.methods)) {
        rows.push({
          method: method.toUpperCase(),
          path: (prefix + layer.route.path).replace(/\/$/, '') || '/',
          auth: rJwt ? 'JWT' : 'public',
          roles: !rJwt ? '—' : rRoles ? rRoles.join(', ') : '(any authenticated role)'
        });
      }
    } else if (layer.name === 'router' && layer.handle.stack) {
      walk(layer.handle.stack, prefix + prefixFromRegexp(layer.regexp), { jwt, roles });
    } else {
      const g = guardOf(layer.handle);
      if (g.jwt) jwt = true;
      if (g.roles) roles = g.roles;
    }
  }
};
walk(app._router.stack, '', { jwt: false, roles: null });
rows.sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method));
return rows;
};

module.exports = { collectRoutes };
if (require.main !== module) return;
const rows = collectRoutes();

const out = ['# API endpoints', '', `Generated by \`node backend/scripts/list-routes.js\` — ${rows.length} routes. Do not edit by hand.`, '',
  'Auth and roles are derived from the middleware actually mounted (router-level and route-level). Ownership/org-scope checks inside controllers are not shown.', '',
  '| Method | Path | Auth | Allowed roles |', '|---|---|---|---|',
  ...rows.map((r) => `| ${r.method} | \`${r.path}\` | ${r.auth} | ${r.roles} |`), ''];
const target = path.join(__dirname, '../../docs/upgrade/API_ENDPOINTS.md');
fs.writeFileSync(target, out.join('\n'));
console.log(`wrote ${rows.length} routes`);
process.exit(0);
